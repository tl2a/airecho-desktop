//! System clipboard: writing received text, and watching for text the user copies.
//!
//! Writing — see [`copy_to_clipboard`]:
//! - macOS: `NSPasteboard` directly — GTK's macOS clipboard backend rejects its own MIME
//!   types and copies nothing.
//! - Linux/Wayland: `wl-copy` (data-control works without focus), GDK otherwise.
//!
//! Watching — see [`watch`]:
//! - macOS has no change notification; the pasteboard's `changeCount` is checked every
//!   500 ms (what macOS clipboard managers do).
//! - Linux: GDK's `changed` signal. On GNOME Wayland, AirEcho prefers XWayland to avoid
//!   Mutter's focused-client-only clipboard change notifications when XWayland is present.
//! - Content marked private by password managers is ignored.

use gtk4::glib;

/// What the watcher reports: plain text the user just copied (not from AirEcho).
pub type OnCopy = Box<dyn Fn(String)>;

// ── Writing ────────────────────────────────────────────────────────────────────

/// Put `text` on the system clipboard (paste anywhere with Cmd/Ctrl+V).
///
/// macOS: written to NSPasteboard directly (stays after AirEcho quits) — GTK's macOS
/// clipboard backend rejects its own MIME types and copies nothing.
#[cfg(target_os = "macos")]
pub fn copy_to_clipboard(text: &str) {
    use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
    use objc2_foundation::NSString;

    let pasteboard = NSPasteboard::generalPasteboard();
    pasteboard.clearContents();
    // SAFETY: reading an immutable AppKit constant
    let string_type = unsafe { NSPasteboardTypeString };
    if !pasteboard.setString_forType(&NSString::from_str(text), string_type) {
        eprintln!("[receiver] could not copy the received text to the clipboard");
    }
}

/// Linux/Wayland: use wl-copy's data-control support so copying works while unfocused
/// when the compositor supports it. Fall back to GDK when wl-copy is unavailable.
#[cfg(target_os = "linux")]
pub fn copy_to_clipboard(text: &str) {
    if std::env::var_os("WAYLAND_DISPLAY").is_some() {
        match copy_with_wl_copy(text) {
            Ok(()) => return,
            Err(err) => eprintln!("[receiver] wl-copy failed ({err}); falling back to GDK"),
        }
    }
    copy_with_gdk(text);
}

/// BSD and other non-macOS platforms: GDK clipboard.
#[cfg(not(any(target_os = "macos", target_os = "linux")))]
pub fn copy_to_clipboard(text: &str) {
    copy_with_gdk(text);
}

#[cfg(not(target_os = "macos"))]
fn copy_with_gdk(text: &str) {
    use gtk4::prelude::*;

    match gtk4::gdk::Display::default() {
        Some(display) => display.clipboard().set_text(text),
        None => eprintln!("[receiver] no display — text not copied to the clipboard"),
    }
}

#[cfg(target_os = "linux")]
fn copy_with_wl_copy(text: &str) -> std::io::Result<()> {
    use std::{
        io::{self, Write},
        process::{Command, Stdio},
    };

    let mut child = Command::new("wl-copy").stdin(Stdio::piped()).spawn()?;
    let mut stdin = child.stdin.take().expect("wl-copy stdin is piped");
    let write_result = stdin.write_all(text.as_bytes());
    drop(stdin);
    let status = child.wait()?;
    write_result?;
    if !status.success() {
        return Err(io::Error::other(format!("exited with {status}")));
    }
    Ok(())
}

// ── Watching ───────────────────────────────────────────────────────────────────

/// Pasteboard types password managers add to mark an entry as private
/// (<http://nspasteboard.org>). Such copies are never sent.
#[cfg(target_os = "macos")]
const PRIVATE_TYPES: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// Call `on_copy` (on the GTK main thread) whenever the user copies text. Copies that
/// happened before this call, and AirEcho's own writes, are not reported.
#[cfg(target_os = "macos")]
pub fn watch(on_copy: OnCopy) {
    use std::cell::Cell;
    use std::time::Duration;

    use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};

    let last_count = Cell::new(NSPasteboard::generalPasteboard().changeCount());
    glib::timeout_add_local(Duration::from_millis(500), move || {
        let pasteboard = NSPasteboard::generalPasteboard();
        let count = pasteboard.changeCount();
        if count == last_count.get() {
            return glib::ControlFlow::Continue;
        }
        last_count.set(count);

        let is_private = pasteboard.types().is_some_and(|types| {
            types.iter().any(|t| PRIVATE_TYPES.contains(&t.to_string().as_str()))
        });
        if is_private {
            println!("[clipboard] ignoring a copy marked private (password manager)");
            return glib::ControlFlow::Continue;
        }
        // SAFETY: reading an immutable AppKit constant
        if let Some(text) = pasteboard.stringForType(unsafe { NSPasteboardTypeString }) {
            on_copy(text.to_string());
        }
        glib::ControlFlow::Continue
    });
}

/// Call `on_copy` (on the GTK main thread) whenever the clipboard text changes. The
/// contents present when the watcher starts are treated as the baseline, not a copy.
#[cfg(not(target_os = "macos"))]
pub fn watch(on_copy: OnCopy) {
    use std::cell::RefCell;
    use std::rc::Rc;

    use gtk4::prelude::*;

    let Some(display) = gtk4::gdk::Display::default() else {
        eprintln!("[clipboard] no display — copied text can't be watched");
        return;
    };
    let clipboard = display.clipboard();
    glib::spawn_future_local(async move {
        let initial = match clipboard.read_text_future().await {
            Ok(text) => text.map(|text| text.to_string()),
            Err(err) => {
                eprintln!("[clipboard] couldn't read initial clipboard contents ({err})");
                None
            }
        };
        let previous = Rc::new(RefCell::new(initial));
        let on_copy: Rc<dyn Fn(String)> = Rc::from(on_copy);
        clipboard.connect_changed(move |clipboard| {
            // KDE password managers mark private entries with this hint
            if clipboard.is_local()
                || clipboard
                    .formats()
                    .contain_mime_type("x-kde-passwordManagerHint")
            {
                return;
            }

            let clipboard = clipboard.clone();
            let previous = previous.clone();
            let on_copy = on_copy.clone();
            glib::spawn_future_local(async move {
                match clipboard.read_text_future().await {
                    Ok(text) => {
                        let text = text.map(|text| text.to_string());
                        if let Some(text) = changed_text(&mut previous.borrow_mut(), text) {
                            on_copy(text);
                        }
                    }
                    Err(err) => eprintln!("[clipboard] couldn't read copied text ({err})"),
                }
            });
        });
    });
}

#[cfg(not(target_os = "macos"))]
fn changed_text(previous: &mut Option<String>, current: Option<String>) -> Option<String> {
    if *previous == current {
        return None;
    }
    *previous = current.clone();
    current
}

#[cfg(test)]
mod tests {
    use super::changed_text;

    #[test]
    fn startup_clipboard_is_not_reported_as_a_copy() {
        let mut previous = Some("already on clipboard".into());
        assert_eq!(
            changed_text(&mut previous, Some("already on clipboard".into())),
            None
        );
        assert_eq!(
            changed_text(&mut previous, Some("copied after startup".into())),
            Some("copied after startup".into())
        );
    }
}
